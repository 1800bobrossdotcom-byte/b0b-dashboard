#!/usr/bin/env python3
"""Write a film's page from its spec: the player shell, plus the script and every source for readers and crawlers.

    python3 scripts/build-film-page.py scripts/film-endgame.json site/endgame.html

The page carries the film's own reel file (spec['js']) and the shared player (site/intro.js). Its meta block sits
between the seo:begin/end markers and is filled by scripts/apply-seo-meta.js from scripts/seo-meta.json - run that
after this. The shot list is generated from the same spec the film is cut from, so the script and the sources a
reader sees are the ones on screen.
"""
import html, json, sys

INTRO_JS = '/intro.js?v=8'
INTRO_CSS = '/intro.css?v=4'


def esc(s):
    return html.escape(s, quote=True)


def main(spec_path, out_path):
    spec = json.load(open(spec_path, encoding='utf-8'))
    film = spec['film']
    title = spec['meta_title']
    name = spec.get('page_name', film['title'])
    parts = spec['parts'] + [dict(spec['finale'], shots=[])]
    script = []
    for p in parts:
        words = ' '.join(L['text'] for L in p['lines'])
        quoted = [s for s in p['shots'] if s['type'] == 'doc' and s.get('bare')]
        if quoted:
            words += ' ' + ' '.join('[%s, on screen:] %s' % (s.get('head', ''), s['text']) for s in quoted)
        script.append('    <li><b>%s. %s</b> &mdash; %s</li>' % (esc(p['id']), esc(p['title']), esc(words)))
    seen, sources = set(), []
    for p in spec['parts']:
        for s in p['shots']:
            if s['type'] == 'doc':
                label = s.get('head') or s.get('word', '')
                sources.append('    <li>DOCUMENT CARD &middot; %s &middot; cited as: %s</li>' % (esc(label), esc(s.get('tag', ''))))
                continue
            for k in s.get('media', []):
                if k in seen:
                    continue
                seen.add(k)
                m = spec['media'][k]
                sources.append('    <li>%s &middot; <a href="%s">source</a></li>'
                               % (esc(m['tag']).replace(' · ', ' &middot; '), esc(m['source_page'])))
    others = ' &middot; '.join('<a href="%s">%s</a>' % (u, t) for u, t in spec.get('page_links', []))
    out = '''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <meta name="theme-color" content="#050505">
  <title>{title}</title>
  <!-- seo:begin (generated by scripts/apply-seo-meta.js from scripts/seo-meta.json - edit there, not here) -->
  <!-- seo:end -->
  <link rel="stylesheet" href="/theme.css">
  <link rel="stylesheet" href="{css}">
  <style>
    html,body{{margin:0;height:100%;background:#050505;color:#e8e4d8}}
    .bi-noscript{{position:fixed;inset:0;display:flex;align-items:center;justify-content:center;padding:24px;
      font-family:var(--mono,monospace);font-size:14px;letter-spacing:.06em;text-align:center;line-height:1.8}}
    .bi-noscript a{{color:#ffcc00}}
    /* The shot list is for readers and crawlers; the film sits over it. */
    .bi-shotlist{{position:absolute;left:-10000px;width:1px;height:1px;overflow:hidden}}
  </style>
</head>
<body>
<div id="b0b-intro" data-mode="page" role="region" aria-label="{aria}"><div class="bi-boot">b0b.dev</div></div>
<noscript><div class="bi-noscript"><p>This film is played by your browser and needs JavaScript.<br><a href="{dl}">Download it (MP4)</a> &middot; <a href="/report">Read the report &rarr;</a></p></div></noscript>

<section class="bi-shotlist" aria-label="Script and sources for the film">
  <h1>{h1}</h1>
  <p>{summary}</p>
  <p><a href="{dl}" download="{dlname}">Download the film</a> (MP4, {w}&times;{h}, subtitles burned in).</p>
  <h2>The script</h2>
  <ol>
{script}
  </ol>
  <h2>Sources, in order of first appearance</h2>
  <ul>
{sources}
  </ul>
  <p>{others}</p>
</section>

<script src="/{js}?v={ver}" defer></script>
<script src="{intro_js}" defer></script>
</body>
</html>
'''.format(title=esc(title), css=INTRO_CSS, aria=esc(name + ', a b0b.dev film'), dl=esc(film['download']),
           dlname=esc(film['downloadName']), h1=esc(name + ' - a b0b.dev film'), summary=spec['page_summary'],
           w=spec['width'], h=spec['height'], script='\n'.join(script), sources='\n'.join(sources), others=others,
           js=spec['js'].split('site/', 1)[1], ver=spec.get('page_version', 1), intro_js=INTRO_JS)
    open(out_path, 'w', encoding='utf-8').write(out)
    print('wrote %s (%d parts, %d sources)' % (out_path, len(script), len(sources)))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
