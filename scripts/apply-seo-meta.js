#!/usr/bin/env node
/**
 * Applies the SEO metadata set to the site's pages.
 *
 * Input: a JSON file of per-page copy ({pages: [{file, title, metaDescription,
 * ogDescription, jsonldType, headline, topics}]}) - the checked-in copy lives
 * at scripts/seo-meta.json, so a copy tweak is: edit that file, re-run this.
 *
 * For each page it removes the noindex directive and any previously managed
 * tags, then writes one managed block (marked seo:begin/seo:end) after the
 * <title>: description, canonical, Open Graph, Twitter card, JSON-LD.
 * Re-running is idempotent - the old block is stripped before the new one is
 * written.
 *
 *   node scripts/apply-seo-meta.js [copy.json]
 */
const fs = require('fs');
const path = require('path');

const HOST = 'https://www.b0b.dev';
const OG_IMAGE = `${HOST}/img/og-card.png`;
const SITE = path.join(__dirname, '..', 'site');

const COPY = JSON.parse(fs.readFileSync(process.argv[2] || path.join(__dirname, 'seo-meta.json'), 'utf8'));

// Canonical URL per file - single source of truth kept in sync with server.js
const URLS = {
  'index.html': '/',
  'report.html': '/report',
  'map.html': '/map',
  'countermeasures.html': '/countermeasures',
  'artifact.html': '/artifact',
  'spectra.html': '/spectra',
  'tones-healing.html': '/tones/healing',
  'tones-protective.html': '/tones/protective',
  'tones-instrument.html': '/tones/instrument',
  'tones-shield.html': '/tones/shield',
  'tones-multipack.html': '/tones/multipack',
  'tones-shield-guide.html': '/tones/shield/guide',
  'ai-attack-vector-analysis.html': '/ai-attack-vector-analysis',
};

// The one honest timestamp on Vercel (see server.js siteUpdatedString).
let modified = null;
try {
  const gen = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'content-integrity-manifest.json'), 'utf8')).generated;
  if (gen && !isNaN(new Date(gen).getTime())) modified = new Date(gen).toISOString();
} catch (e) { /* omit rather than invent */ }

function esc(t) {
  return String(t).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function jsonld(p, url) {
  const base = {
    '@context': 'https://schema.org',
    '@type': p.jsonldType,
    name: p.headline,
    url,
    description: p.metaDescription,
    image: OG_IMAGE,
  };
  if (p.jsonldType === 'WebSite') {
    return [base];
  }
  base.isPartOf = { '@type': 'WebSite', name: 'b0b.dev', url: `${HOST}/` };
  if (p.jsonldType === 'Article') {
    base.headline = p.headline;
    base.author = { '@type': 'Person', name: 'b0b' };
    base.publisher = { '@type': 'Organization', name: 'b0b.dev', url: `${HOST}/` };
    base.mainEntityOfPage = url;
    if (modified) base.dateModified = modified;
  }
  if (p.jsonldType === 'WebApplication') {
    base.applicationCategory = 'UtilityApplication';
    base.operatingSystem = 'Web';
    base.offers = { '@type': 'Offer', price: '0', priceCurrency: 'USD' };
  }
  const blocks = [base];
  // The field guide is the one page with a real intermediate URL above it.
  if (p.file === 'tones-shield-guide.html') {
    blocks.push({
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'b0b.dev', item: `${HOST}/` },
        { '@type': 'ListItem', position: 2, name: 'ARC Shield', item: `${HOST}/tones/shield` },
        { '@type': 'ListItem', position: 3, name: 'Field Guide', item: url },
      ],
    });
  }
  return blocks;
}

let failures = 0;
for (const p of COPY.pages) {
  const url = HOST + URLS[p.file];
  if (!URLS[p.file]) { console.error(`SKIP ${p.file}: no canonical URL mapped`); failures++; continue; }
  const f = path.join(SITE, p.file);
  let s = fs.readFileSync(f, 'utf8');

  // 1. Strip a previous managed block (idempotence).
  // The opening marker carries a "(generated by ...)" note, so this must match
  // seo:begin followed by anything up to the close - an earlier version
  // anchored on a bare "<!-- seo:begin -->", matched nothing, and silently
  // appended a second block on every re-run instead of replacing the first.
  s = s.replace(/[ \t]*<!-- seo:begin[\s\S]*?<!-- seo:end -->\n?/g, '');

  // 2. Strip the tags this block replaces: noindex, description, og/twitter, canonical.
  s = s.replace(/[ \t]*<meta name="robots"[^>]*>\n?/g, '');
  s = s.replace(/[ \t]*<meta name="description"[^>]*>\n?/g, '');
  s = s.replace(/[ \t]*<meta property="og:[^"]*"[^>]*>\n?/g, '');
  s = s.replace(/[ \t]*<meta name="twitter:[^"]*"[^>]*>\n?/g, '');
  s = s.replace(/[ \t]*<link rel="canonical"[^>]*>\n?/g, '');

  // 3. Replace the title.
  if (!/<title>[\s\S]*?<\/title>/.test(s)) { console.error(`FAIL ${p.file}: no <title>`); failures++; continue; }
  s = s.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(p.title)}</title>`);

  // 4. Managed block after the title.
  const ld = jsonld(p, url)
    .map((b) => `  <script type="application/ld+json">${JSON.stringify(b)}</script>`)
    .join('\n');
  const ogType = p.jsonldType === 'Article' ? 'article' : 'website';
  const block = `  <!-- seo:begin (generated by scripts/apply-seo-meta.js from scripts/seo-meta.json - edit there, not here) -->
  <meta name="description" content="${esc(p.metaDescription)}">
  <link rel="canonical" href="${url}">
  <meta property="og:site_name" content="b0b.dev">
  <meta property="og:title" content="${esc(p.title)}">
  <meta property="og:description" content="${esc(p.ogDescription)}">
  <meta property="og:type" content="${ogType}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${OG_IMAGE}">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(p.title)}">
  <meta name="twitter:description" content="${esc(p.ogDescription)}">
  <meta name="twitter:image" content="${OG_IMAGE}">
${ld}
  <!-- seo:end -->`;
  s = s.replace(/<\/title>\n?/, `</title>\n${block}\n`);

  fs.writeFileSync(f, s);
  console.log(`ok   ${p.file}  "${p.title}"`);
}
if (failures) process.exit(1);
console.log(`\napplied ${COPY.pages.length} pages`);
